# Embed templates/visit_template.docx as text parts in assets/visit_template.js so the page can
# build the filled .docx in the browser without fetching files or loading a zip library.
# Re-run after editing the template:  python scripts/embed_template.py
import json, sys, zipfile
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = root / "templates" / "visit_template.docx"
out = root / "assets" / "visit_template.js"

parts = []
with zipfile.ZipFile(src) as z:
    for info in z.infolist():
        data = z.read(info.filename)
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            sys.exit(f"{info.filename} is binary; the browser zip writer only handles text parts")
        parts.append({"name": info.filename, "text": text})

out.write_text(
    "// Generated by scripts/embed_template.py from templates/visit_template.docx — do not edit by hand.\n"
    "window.VISIT_TEMPLATE = " + json.dumps(parts, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"wrote {out.relative_to(root)} ({len(parts)} parts)")
